#!/usr/bin/env python3
"""Generate the RoleDefinition seed SQL from docs/canonical-role-map.md.

Ticket 0056 (M03) requires RoleDefinition to be "seeded from the 44
canonical roles in docs/canonical-role-map.md (migration or seed script,
not hand enumerated twice)". This script is the single place that reads
that table; its output is pasted into the seed migration so the 44 (+3
platform-only) roles are never retyped by hand a second time. Re-run and
re-paste if canonical-role-map.md changes.

Usage: python3 scripts/generate_role_seed.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP_PATH = ROOT / "docs" / "canonical-role-map.md"

SECTION_RE = re.compile(r"^## (.+?)(?: \(\d+ rows.*\))?$")
CATALOGUE_ROW_RE = re.compile(
    r"^\|\s*(?P<raw_label>.+?)\s*\|\s*`(?P<role_id>role\.[a-z0-9_]+)`\s*\|\s*(?P<persona>.+?)\s*\|\s*(?P<count>\d+)\s*\|$"
)
PLATFORM_ROW_RE = re.compile(
    r"^\|\s*`(?P<role_id>role\.[a-z0-9_]+)`\s*\|\s*(?P<persona>.+?)\s*\|$"
)


def sql_quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    lines = MAP_PATH.read_text().splitlines()
    section = None
    rows = []  # (role_id, label, department_cluster, persona, is_platform, source_row_count)

    for line in lines:
        m = SECTION_RE.match(line.strip())
        if m:
            section = m.group(1).strip()
            continue

        if section == "Platform-only roles (not in the source catalogue)":
            m = PLATFORM_ROW_RE.match(line.strip())
            if m:
                rows.append((m.group("role_id"), None, "Platform", m.group("persona"), True, 0))
            continue

        m = CATALOGUE_ROW_RE.match(line.strip())
        if m and section and section not in ("How to read this table", "Notes and follow-ups"):
            rows.append(
                (
                    m.group("role_id"),
                    m.group("raw_label"),
                    section,
                    m.group("persona"),
                    False,
                    int(m.group("count")),
                )
            )

    catalogue_rows = [r for r in rows if not r[4]]
    platform_rows = [r for r in rows if r[4]]
    assert len(catalogue_rows) == 44, f"expected 44 canonical catalogue roles, found {len(catalogue_rows)}"
    assert len(platform_rows) == 3, f"expected 3 platform-only roles, found {len(platform_rows)}"

    print(f"-- Generated by scripts/generate_role_seed.py from docs/canonical-role-map.md")
    print(f"-- {len(catalogue_rows)} canonical catalogue roles + {len(platform_rows)} platform-only roles.")
    print("insert into public.role_definitions")
    print("  (id, label, department_cluster, brd_persona, is_platform_role, source_row_count)")
    print("values")
    value_lines = []
    for role_id, label, cluster, persona, is_platform, count in rows:
        display_label = label if label is not None else persona
        value_lines.append(
            "  ("
            f"{sql_quote(role_id)}, {sql_quote(display_label)}, {sql_quote(cluster)}, "
            f"{sql_quote(persona)}, {str(is_platform).lower()}, {count}"
            ")"
        )
    print(",\n".join(value_lines) + ";")


if __name__ == "__main__":
    main()
